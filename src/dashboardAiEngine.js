function createProfile({
  title,
  level,
  domain,
  keywords,
  metrics,
  questions,
  kpis,
  priorityRoles,
  gadgetTitles = {},
  visuals = {},
}) {
  return {
    title,
    level,
    domain,
    keywords: [title, ...(keywords || [])].map(value => String(value).toLowerCase()),
    metrics,
    questions,
    kpis,
    priorityRoles,
    gadgetTitles: { ...DEFAULT_GADGET_TITLES, ...gadgetTitles },
    visuals: { ...DEFAULT_GADGET_VISUALS, ...visuals },
  };
}

function createTemplateProfile({
  title,
  level = 'Team',
  domain,
  keywords,
  metrics,
  questions,
  kpis,
  priorityRoles,
  gadgetTitles,
  visuals = {},
}) {
  const summaryTitle = `${String(title || 'Dashboard').replace(/\s+Dashboard$/i, '')} Summary`;
  return createProfile({
    title,
    level,
    domain,
    keywords,
    metrics,
    questions,
    kpis,
    priorityRoles,
    gadgetTitles: {
      'forge-summary': summaryTitle,
      ...gadgetTitles,
    },
    visuals: {
      'forge-summary': 'template-summary-grid',
      ...visuals,
    },
  });
}

