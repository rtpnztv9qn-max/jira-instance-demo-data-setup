function mergeProfiles(selectedProfiles) {
  const [primaryKey, primaryProfile] = selectedProfiles[0];
  const mergedRoles = Array.from(new Set(selectedProfiles.flatMap(([, profile]) => profile.priorityRoles)));

  return {
    profile: primaryKey,
    title: selectedProfiles.length === 1 ? primaryProfile.title : 'Multi-focus Dashboard',
    level: selectedProfiles.length === 1 ? primaryProfile.level : 'Multi-focus',
    domain: selectedProfiles.length === 1 ? primaryProfile.domain : primaryProfile.domain,
    metrics: Array.from(new Set(selectedProfiles.flatMap(([, profile]) => profile.metrics))).slice(0, 8),
    questions: Array.from(new Set(selectedProfiles.flatMap(([, profile]) => profile.questions))).slice(0, 4),
    kpis: Array.from(new Set(selectedProfiles.flatMap(([, profile]) => profile.kpis))).slice(0, 5),
    priorityRoles: mergedRoles.slice(0, 6),
    gadgetTitles: Object.assign({}, ...selectedProfiles.map(([, profile]) => profile.gadgetTitles)),
    visuals: Object.assign({}, ...selectedProfiles.map(([, profile]) => profile.visuals)),
    sectionLabels: Object.assign({}, ...selectedProfiles.map(([profileKey, profile]) => (
      Object.fromEntries(profile.priorityRoles.map(role => [
        role,
        PROFILE_ROLE_OVERRIDES[profileKey]?.[role]?.sectionLabel || ROLE_SECTION_LABELS[role] || 'Dashboard Section',
      ]))
    ))),
  };
}

export function inferDashboardIntent(prompt, industry, selectedValue = '') {
  const normalizedPrompt = String(prompt || '').toLowerCase();
  const normalizedValue = String(selectedValue || '').toLowerCase();
  const exactProfile = DASHBOARD_PROFILES[normalizedValue];
  const matches = exactProfile
    ? [[normalizedValue, exactProfile]]
    : Object.entries(DASHBOARD_PROFILES)
      .filter(([key]) => key !== 'operational')
      .filter(([, value]) => value.keywords.some(keyword => normalizedPrompt.includes(keyword)));

  const selectedProfiles = matches.length > 0 ? matches : [['operational', DASHBOARD_PROFILES.operational]];
  const merged = mergeProfiles(selectedProfiles);

  return {
    ...merged,
    prompt: String(prompt || '').trim(),
    industry,
  };
}

export function orderDashboardGadgetPlans(plans, dashboardIntent) {
  const intentRoles = dashboardIntent?.priorityRoles || DASHBOARD_PROFILES.operational.priorityRoles;
  const reportAlternates = [
    'forge-overdue',
    'forge-projects',
    'forge-average-time-status',
    'forge-ticket-aging',
    'forge-roadmap',
    'forge-priority',
    'forge-created-resolved',
    'forge-status',
  ];
  const normalizedIntentRoles = intentRoles.includes('forge-open-work') && intentRoles.includes('forge-reports')
    ? intentRoles.map(role => {
      if (role !== 'forge-reports') {
        return role;
      }
      return reportAlternates.find(candidate => !intentRoles.includes(candidate)) || null;
    }).filter(Boolean)
    : intentRoles;
  const roles = ['forge-summary', ...normalizedIntentRoles.filter(role => role !== 'forge-summary')];
  const byRole = new Map(plans.map(plan => [plan.role, plan]));

  return roles
    .map(role => byRole.get(role))
    .filter(Boolean)
    .map(plan => ({
      ...PROFILE_ROLE_OVERRIDES[dashboardIntent?.profile]?.[plan.role],
      ...plan,
      title: PROFILE_ROLE_OVERRIDES[dashboardIntent?.profile]?.[plan.role]?.title || dashboardIntent?.gadgetTitles?.[plan.role] || plan.title,
      subtitle: dashboardIntent?.questions?.[0] || '',
      visualType: PROFILE_ROLE_OVERRIDES[dashboardIntent?.profile]?.[plan.role]?.visualType || dashboardIntent?.visuals?.[plan.role] || DEFAULT_GADGET_VISUALS[plan.role] || 'standard',
      sectionLabel: PROFILE_ROLE_OVERRIDES[dashboardIntent?.profile]?.[plan.role]?.sectionLabel || dashboardIntent?.sectionLabels?.[plan.role] || ROLE_SECTION_LABELS[plan.role] || 'Dashboard Section',
    }));
}

export function buildDashboardName(config, runLabel) {
  const intentTitle = config.dashboardIntent?.title || 'Release Dashboard';
  return `${config.environmentName} - ${intentTitle} (${runLabel})`;
}
